"""`fsf init`: start a real site from an example and generate its credentials.

    fsf init my-site --from sites/examples/houseplants

Writes sites/local/<name>/ (the whole folder is gitignored):

    site.yaml            the example with its id changed; edit nodes, runtimes and plantings
    secrets.yaml         for the node firmware: WiFi, OTA password, one broker login per node
    hub.env, web.env, operator.env
                         broker logins for the hub, the dashboard and the fsf command line
    broker/passwd        Mosquitto password file (hashes only)
    broker/acl           who may read and write which topics

Running it again keeps every password it finds and only adds what is missing, for
example after a node was added to the site file.
"""

from __future__ import annotations

import base64
import hashlib
import re
import secrets
from pathlib import Path

import yaml

from .catalog import Catalog, load_site
from .firmware import ident

PBKDF2_ITERATIONS = 101     # what mosquitto_passwd uses for its $7$ hashes


class InitError(Exception):
    pass


def mosquitto_hash(password: str, salt: bytes | None = None) -> str:
    """A password-file entry as mosquitto_passwd writes it: $7$<iterations>$<salt>$<PBKDF2-SHA512>."""
    salt = salt or secrets.token_bytes(12)
    digest = hashlib.pbkdf2_hmac("sha512", password.encode(), salt, PBKDF2_ITERATIONS, dklen=64)
    return f"$7${PBKDF2_ITERATIONS}${base64.b64encode(salt).decode()}${base64.b64encode(digest).decode()}"


def acl(site_id: str, nodes: list[str]) -> str:
    """Least privilege per login. A node can publish only under its own name and hear only its own commands."""
    root = f"fsf/{site_id}"
    lines = ["# Generated by `fsf init`. Mosquitto denies everything not listed here.", "",
             "user hub", f"topic readwrite {root}/#", "",
             "# The dashboard reads everything and can only ask the hub to act.",
             "user web", f"topic read {root}/#", f"topic write {root}/hub/cmd", "",
             "# The fsf command line: bench, calibrate, node test, doctor.",
             "user operator", f"topic readwrite {root}/#", ""]
    for node in nodes:
        lines += [f"user node-{node}", f"topic write {root}/{node}/#", f"topic read {root}/{node}/+/cmd", ""]
    return "\n".join(lines)


def _read_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    pairs = (line.split("=", 1) for line in path.read_text(encoding="utf-8").splitlines() if "=" in line and not line.startswith("#"))
    return {k.strip(): v.strip() for k, v in pairs}


def init(name: str, source: Path, root: Path, catalog: Catalog, target: Path | None = None) -> list[Path]:
    if not re.fullmatch(r"[a-z0-9][a-z0-9._-]*", name):
        raise InitError("the site name may contain only lowercase letters, digits, dots, hyphens and underscores")
    folder = target or root / "sites" / "local" / name
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "broker").mkdir(exist_ok=True)
    written: list[Path] = []

    site_file = folder / "site.yaml"
    if not site_file.exists():
        source_file = source / "site.yaml" if source.is_dir() else source
        if not source_file.exists():
            raise InitError(f"{source_file} does not exist")
        text, count = re.subn(r"(?m)^id:\s*\S+", f"id: {name}", source_file.read_text(encoding="utf-8"), count=1)
        if count != 1:
            raise InitError(f"{source_file} has no top-level id")
        site_file.write_text(text, encoding="utf-8", newline="\n")
        written.append(site_file)
    site = load_site(site_file, catalog)
    nodes = site.nodes

    # -- firmware secrets: keep what is there, add what is missing
    secrets_file = folder / "secrets.yaml"
    known = yaml.safe_load(secrets_file.read_text(encoding="utf-8")) or {} if secrets_file.exists() else {}
    values = {"wifi_ssid": "", "wifi_password": "", "mqtt_host": "", "ota_password": secrets.token_urlsafe(18)}
    for node in nodes:
        values[f"{ident(node)}_mqtt_username"] = f"node-{node}"
        values[f"{ident(node)}_mqtt_password"] = secrets.token_urlsafe(18)
    values.update({k: v for k, v in known.items() if v not in (None, "") or k in ("wifi_ssid", "wifi_password", "mqtt_host")})
    head = ("# Generated by `fsf init`. Never commit this file.\n"
            "# Fill in wifi_ssid, wifi_password and mqtt_host (the hub's address as the nodes see it).\n")
    secrets_file.write_text(head + yaml.safe_dump(values, sort_keys=False), encoding="utf-8", newline="\n")
    written.append(secrets_file)

    # -- logins of the services on the hub host
    logins = {f"node-{node}": values[f"{ident(node)}_mqtt_password"] for node in nodes}
    for service in ("hub", "web", "operator"):
        env_file = folder / f"{service}.env"
        env = _read_env(env_file)
        env.setdefault("FSF_MQTT_USERNAME", service)
        env.setdefault("FSF_MQTT_PASSWORD", secrets.token_urlsafe(18))
        if service == "web":
            env.setdefault("FSF_WEB_PASSWORD_HASH", "")
        note = ("# Make the dashboard password hash with: python -m fsf_web hash-password\n" if service == "web" else "")
        env_file.write_text("# Generated by `fsf init`. Never commit this file.\n" + note
                            + "".join(f"{k}={v}\n" for k, v in env.items()), encoding="utf-8", newline="\n")
        written.append(env_file)
        logins[service] = env["FSF_MQTT_PASSWORD"]

    passwd = folder / "broker" / "passwd"
    passwd.write_text("".join(f"{user}:{mosquitto_hash(password)}\n" for user, password in sorted(logins.items())),
                      encoding="utf-8", newline="\n")
    acl_file = folder / "broker" / "acl"
    acl_file.write_text(acl(site.id, nodes), encoding="utf-8", newline="\n")
    written += [passwd, acl_file]
    return written
