"""Generate one ESPHome config per node from a site file.

    fsf firmware build sites/local/my-site

Each device's block comes from its model's ESPHome driver template in catalog/models/.
Around those the generator adds what makes the node speak the MQTT contract
(fsf_core/topics.py, schemas/mqtt/): the status topic as birth and last will, one state
message per device, and for every actuator a command handler whose on-command starts a
lease that the node itself ends. Everything is off after a reboot.

Secrets are never written: the configs refer to `!secret` names, and a
`secrets.example.yaml` lists them.
"""

from __future__ import annotations

import re
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from .. import topics
from ..catalog import Catalog, Device, Site

HEADER = "fsf_node.h"
REPORT_INTERVAL = "60s"
SECRETS = {
    "wifi_ssid": "name of the 2.4 GHz network the node joins",
    "wifi_password": "its password",
    "ota_password": "password for over-the-air updates of the nodes",
    "mqtt_host": "address of the broker, as seen from the node",
}


def node_secrets(node_id: str) -> dict[str, str]:
    """Every node has its own broker login, so the broker can restrict it to its own topics."""
    return {f"{ident(node_id)}_mqtt_username": f"broker user of node {node_id} (fsf init makes it node-{node_id})",
            f"{ident(node_id)}_mqtt_password": "its password"}
REFUSED = "actuators accept on (with duration_s) and off"


class FirmwareError(Exception):
    def __init__(self, problems: list[str]):
        self.problems = problems
        super().__init__("\n".join(problems))


class Secret(str):
    """Rendered as `!secret name`."""


class Lambda(str):
    """Rendered as a `!lambda` block."""


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


_Dumper.add_representer(Secret, lambda d, v: d.represent_scalar("!secret", str(v)))
_Dumper.add_representer(Lambda, lambda d, v: d.represent_scalar("!lambda", str(v), style="|" if "\n" in v else None))
_Dumper.add_representer(str, lambda d, v: d.represent_scalar("tag:yaml.org,2002:str", v, style="|" if "\n" in v else None))


@dataclass
class NodeBuild:
    node: str
    config: dict
    warnings: list[str] = field(default_factory=list)

    def render(self, source: str) -> str:
        head = (f"# Generated by `fsf firmware build` from {source}.\n"
                "# Do not edit: change the site file or the model templates and build again.\n")
        return head + yaml.dump(self.config, Dumper=_Dumper, sort_keys=False, default_flow_style=False, width=140)


def ident(device_id: str) -> str:
    """A device id as a C++ identifier."""
    name = re.sub(r"[^a-z0-9]", "_", device_id.lower())
    return name if name[0].isalpha() else f"d_{name}"


def _fill(template: str, values: dict[str, str], where: str, problems: list[str]) -> dict:
    def replace(match: re.Match) -> str:
        key = match.group(1)
        if key not in values:
            problems.append(f"{where}: template needs ${{{key}}}, which the site file does not give")
            return "0"
        return str(values[key])
    return yaml.safe_load(re.sub(r"\$\{([a-z0-9_.]+)\}", replace, template)) or {}


def _merge(config: dict, snippet: dict) -> None:
    for key, items in snippet.items():
        config.setdefault(key, []).extend(items if isinstance(items, list) else [items])


def _ids(node) -> set[str]:
    """Every `id:` value in a rendered snippet."""
    found: set[str] = set()
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "id" and isinstance(value, str):
                found.add(value)
            else:
                found |= _ids(value)
    elif isinstance(node, list):
        for item in node:
            found |= _ids(item)
    return found


def _publish(topic: str, body: str, retain: bool = False) -> dict:
    action = {"topic": topic, "payload": Lambda(body)}
    if retain:
        action["retain"] = True
    return {"mqtt.publish_json": action}


def _ack(topic: str, ok: bool, error: str | None = None) -> dict:
    body = f'root["id"] = x["id"];\nroot["ok"] = {"true" if ok else "false"};'
    if error:
        body += f'\nroot["error"] = "{error}";'
    return _publish(topic, body)


def build_node(site: Site, catalog: Catalog, node: dict) -> NodeBuild:
    """The ESPHome config of one node as a dict, or FirmwareError listing everything that is missing."""
    problems: list[str] = []
    warnings: list[str] = []
    node_id, sid = node["id"], site.id
    board = catalog.get("Board", node["board"])
    target = board.get("esphome")
    if not target:
        raise FirmwareError([f"node {node_id}: board {board['id']} has no esphome platform in catalog/boards/"])
    name = f"{sid}-{node_id}" if len(f"{sid}-{node_id}") <= 31 else node_id
    if len(name) > 31 or not re.fullmatch(r"[a-z0-9-]+", name):
        problems.append(f"node {node_id}: ESPHome needs a name of at most 31 letters, digits and hyphens; got {name!r}")

    devices = [d for d in site.devices.values() if d.node == node_id]
    components = catalog.items["Component"]
    parts: dict = {}                                    # sensor:, switch:, output:, light:, ... from the templates
    i2c: dict[str, set[str]] = {"sda": set(), "scl": set()}
    sensors: list[tuple[Device, list[str]]] = []
    actuators: list[tuple[Device, dict]] = []
    strips: list[Device] = []

    for dev in devices:
        where = f"device {dev.id}"
        driver = next((d for d in dev.model["drivers"] if d["runtime"] == "esphome"), None)
        signals = {s["signal"]: s for s in dev.model.get("pins", [])}
        if driver is None or "template" not in driver:
            if dev.model["interface"]["bus"] == "mains_relay":
                warnings.append(f"{where}: mains load, not in the firmware. Put it on a smart power strip node "
                                "(board tplink.kasa-hs300), which the fsf_kasa bridge controls")
            elif signals:
                problems.append(f"{where}: model {dev.model['id']} has no ESPHome template")
            continue
        pins = dev.raw.get("pins", {})
        values = {"id": ident(dev.id), "led_count": dev.raw.get("led_count", 0),
                  **{f"cal.{k}": v for k, v in dev.raw.get("calibration", {}).items()}}
        for signal, spec in signals.items():
            pin = pins.get(signal)
            if pin is None:
                problems.append(f"{where}: no pin for {signal}; run `fsf validate --pins` for a proposal")
                continue
            if spec["needs"] in ("i2c_sda", "i2c_scl"):
                i2c[spec["needs"][4:]].add(pin)
            elif "/" in pin:
                provider_id, channel = pin.split("/")
                provider = site.devices[provider_id]
                offered = next((d for d in provider.model["drivers"] if d["runtime"] == "esphome"), {})
                snippet = offered.get("provides_templates", {}).get(spec["needs"])
                if snippet is None:
                    problems.append(f"{where}: model {provider.model['id']} has no ESPHome template for its {spec['needs']} channels")
                    continue
                _merge(parts, _fill(snippet, {**values, "provider": ident(provider_id), "channel": channel}, where, problems))
            else:
                values[f"pin.{signal}"] = pin
                if signal in driver.get("signal_templates", {}):
                    _merge(parts, _fill(driver["signal_templates"][signal], values, where, problems))
        snippet = _fill(driver["template"], values, where, problems)
        _merge(parts, snippet)

        if dev.cls == "sensor":
            wanted = [m["quantity"] for role in dev.roles for m in components[role].get("measures", [])]
            have = [q for q in wanted if f"{ident(dev.id)}_{q}" in _ids(snippet)]
            if have and f"{ident(dev.id)}_raw" in _ids(parts):
                have.append("raw")                      # the uncalibrated value, which `fsf calibrate` reads
            if have:
                sensors.append((dev, have))
            elif not dev.model.get("provides"):
                problems.append(f"{where}: the template of {dev.model['id']} defines none of {', '.join(wanted)}")
        elif dev.cls == "actuator":
            if "control" not in driver:
                problems.append(f"{where}: the ESPHome driver of {dev.model['id']} does not say what to switch (control)")
            else:
                actuators.append((dev, driver["control"]))
        elif "indicator.led_strip" in dev.roles:
            strips.append(dev)

    if len(strips) > 1:
        problems.append(f"node {node_id}: one status strip per node is supported; found {', '.join(d.id for d in strips)}")
    for line in ("sda", "scl"):
        if len(i2c[line]) > 1:
            problems.append(f"node {node_id}: I2C devices must share one {line.upper()} pin; found {', '.join(sorted(i2c[line]))}")
    if bool(i2c["sda"]) != bool(i2c["scl"]):
        problems.append(f"node {node_id}: I2C needs both SDA and SCL")
    if problems:
        raise FirmwareError(problems)

    def topic(dev: Device, leaf: str) -> str:
        return topics.device(sid, node_id, dev.id, leaf)

    scripts, handlers, on_connect, reports = [], [], [], []
    for dev, control in actuators:
        name_id = ident(dev.id)
        if control["type"] == "switch":
            turn_on = [{"switch.turn_on": f"{name_id}_switch"}]
            turn_off = [{"switch.turn_off": f"{name_id}_switch"}]
        else:
            outputs = [f"{name_id}_{out}" for out in control["outputs"]]
            turn_on = [{"output.set_level": {"id": out, "level": Lambda("return level;")}} for out in outputs]
            turn_off = [{"output.turn_off": out} for out in outputs]
        state_on = _publish(topic(dev, "state"), 'root["t"] = fsf_now();\nroot["on"] = true;\nroot["level"] = level;', retain=True)
        state_off = _publish(topic(dev, "state"), 'root["t"] = fsf_now();\nroot["on"] = false;', retain=True)
        scripts.append({
            "id": f"{name_id}_lease", "mode": "restart", "parameters": {"duration_ms": "int", "level": "float"},
            # The lease: on, wait, off. Runs on the node, so it ends even if WiFi or the hub is gone.
            "then": [*turn_on, state_on, {"delay": Lambda("return duration_ms;")}, *turn_off, state_off]})
        handlers.append({"topic": topic(dev, "cmd"), "then": [{"if": {
            "condition": {"lambda": Lambda("return fsf_is_on(x);")},
            "then": [{"script.execute": {"id": f"{name_id}_lease", "duration_ms": Lambda("return fsf_duration_ms(x);"),
                                         "level": Lambda("return fsf_level(x);")}},
                     _ack(topic(dev, "ack"), True)],
            "else": [{"if": {
                "condition": {"lambda": Lambda('return fsf_is(x, "off");')},
                "then": [{"script.stop": f"{name_id}_lease"}, *turn_off, state_off, _ack(topic(dev, "ack"), True)],
                "else": [_ack(topic(dev, "ack"), False, REFUSED)]}}]}}]})
        on_connect.append(_publish(topic(dev, "state"),
                                   f'root["t"] = fsf_now();\nroot["on"] = id({name_id}_lease).is_running();', retain=True))

    for dev in strips:
        handlers.append({"topic": topic(dev, "cmd"), "then": [{"if": {
            "condition": {"lambda": Lambda('return fsf_is(x, "render");')},
            "then": [{"lambda": Lambda("fsf_render(x);")},
                     _publish(topic(dev, "state"), 'root["t"] = fsf_now();\nroot["brightness"] = x["brightness"];\n'
                                                   'root["segments"] = x["segments"];', retain=True),
                     _ack(topic(dev, "ack"), True)],
            "else": [_ack(topic(dev, "ack"), False, "LED strips accept render")]}}]})

    for dev, quantities in sensors:
        entities = [(q, f"id({ident(dev.id)}_{q}).state") for q in quantities]
        body = 'root["t"] = fsf_now();\n' + "\n".join(
            f'if (!isnan({value})) root["{q}"] = {"fsf_round3" if q == "raw" else "fsf_round2"}({value});' for q, value in entities)
        # A device with nothing valid to say stays silent, so the hub sees it go stale.
        measured = [v for q, v in entities if q != "raw"]
        reports.append({"if": {"condition": {"lambda": Lambda("return " + " || ".join(f"!isnan({v})" for v in measured) + ";")},
                               "then": [_publish(topic(dev, "state"), body, retain=True)]}})

    status = topics.node_status(sid, node_id)
    esphome: dict = {"name": name, "friendly_name": f"{sid} {node_id}", "includes": [HEADER]}
    if strips:
        esphome["on_boot"] = {"priority": -100, "then": [{"light.turn_on": {
            "id": f"{ident(strips[0].id)}_light", "brightness": "100%", "effect": "status"}}]}
    platform: dict = {"board": target["board"]}
    if "framework" in target:
        platform["framework"] = {"type": target["framework"]}
    mqtt: dict = {
        "broker": Secret("mqtt_host"), "username": Secret(f"{ident(node_id)}_mqtt_username"),
        "password": Secret(f"{ident(node_id)}_mqtt_password"),
        "client_id": f"fsf-{sid}-{node_id}", "discovery": False, "log_topic": None,
        "topic_prefix": f"{topics.ROOT}/{sid}/{node_id}/esphome",
        "birth_message": {"topic": status, "payload": "online", "retain": True},
        "will_message": {"topic": status, "payload": "offline", "retain": True}}
    if on_connect:
        mqtt["on_connect"] = {"then": on_connect}
    if handlers:
        mqtt["on_json_message"] = handlers
    config: dict = {
        "esphome": esphome, target["platform"]: platform, "logger": {},
        "wifi": {"ssid": Secret("wifi_ssid"), "password": Secret("wifi_password")},
        "ota": [{"platform": "esphome", "password": Secret("ota_password")}],
        "time": [{"platform": "sntp", "id": "fsf_time"}],
        "mqtt": mqtt}
    if i2c["sda"]:
        config["i2c"] = {"sda": next(iter(i2c["sda"])), "scl": next(iter(i2c["scl"]))}
    config.update(parts)
    if scripts:
        config["script"] = scripts
    if reports:
        config["interval"] = [{"interval": REPORT_INTERVAL, "then": reports}]
    return NodeBuild(node_id, config, warnings)


def buildable(site: Site, catalog: Catalog, include_sim: bool = False) -> list[dict]:
    """Nodes that run ESPHome, plus simulated nodes whose board could, when asked."""
    out = []
    for node in site.raw["nodes"]:
        board = catalog.get("Board", node["board"])
        if node["runtime"] == "esphome" or (include_sim and node["runtime"] == "sim" and "esphome" in board.get("runtimes", [])):
            out.append(node)
    return out


def build(site: Site, catalog: Catalog, out_dir: Path, source: str, include_sim: bool = False,
          secrets_file: Path | None = None) -> tuple[list[Path], list[str]]:
    """Write <node>.yaml for every buildable node, the shared header and secrets.example.yaml.

    secrets_file: the site's own secrets.yaml (from `fsf init`); copied next to the configs,
    which is where ESPHome looks for it. The output folder is gitignored.
    """
    nodes = buildable(site, catalog, include_sim)
    if not nodes:
        raise FirmwareError([f"site {site.id} has no node with runtime esphome "
                             "(simulated nodes are skipped unless you pass --include-sim)"])
    builds, problems = [], []
    for node in nodes:
        try:
            builds.append(build_node(site, catalog, node))
        except FirmwareError as err:
            problems += err.problems
    if problems:
        raise FirmwareError(problems)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for item in builds:
        path = out_dir / f"{item.node}.yaml"
        path.write_text(item.render(source), encoding="utf-8", newline="\n")
        written.append(path)
    shutil.copyfile(Path(__file__).parent / HEADER, out_dir / HEADER)
    keys = dict(SECRETS)
    for item in builds:
        keys.update(node_secrets(item.node))
    example = ("# Copy to secrets.yaml in this folder and fill in, or let `fsf init` generate it. Never commit secrets.yaml.\n"
               + "".join(f'{key}: ""    # {meaning}\n' for key, meaning in keys.items()))
    (out_dir / "secrets.example.yaml").write_text(example, encoding="utf-8", newline="\n")
    if secrets_file is not None and secrets_file.exists():
        shutil.copyfile(secrets_file, out_dir / "secrets.yaml")
    return written, [w for item in builds for w in item.warnings]


def flash(config: Path, device: str | None = None) -> int:
    """Compile and upload one node with the ESPHome command line (USB the first time, then over the air)."""
    if not config.exists():
        raise FirmwareError([f"{config} does not exist; run `fsf firmware build` first"])
    if not (config.parent / "secrets.yaml").exists():
        raise FirmwareError([f"{config.parent / 'secrets.yaml'} is missing; copy secrets.example.yaml and fill it in"])
    if shutil.which("esphome") is None:
        raise FirmwareError(["the esphome command was not found; install it with `pip install esphome`"])
    command = ["esphome", "run", str(config)] + (["--device", device] if device else [])
    return subprocess.call(command)
